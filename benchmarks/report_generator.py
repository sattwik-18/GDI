"""Benchmark report generator producing machine-readable JSON and Markdown dashboards."""

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


class BenchmarkReportGenerator:
    """Generates structured JSON benchmark reports and human-readable Markdown summaries."""

    def generate_json(self, benchmark_data: dict[str, Any], output_path: str) -> None:
        """Saves machine-readable JSON report."""
        payload = {
            "title": "GDI Prototype 1 Benchmark Report",
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "metrics": benchmark_data,
        }
        p = Path(output_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    def generate_markdown(self, benchmark_data: dict[str, Any], output_path: str) -> None:
        """Saves formatted Markdown dashboard report."""
        lines = [
            "# GDI Prototype 1 — Performance Benchmark Dashboard",
            "",
            f"**Generated:** {datetime.now(timezone.utc).isoformat()}  ",
            f"**Total Documents Evaluated:** {benchmark_data.get('documents_evaluated', 0)}  ",
            f"**End-to-End Total Duration:** {benchmark_data.get('total_duration_ms', 0.0):.2f} ms",
            "",
            "## Stage-by-Stage Latency & Resource Breakdown",
            "",
            "| Stage Name | Mean Latency (ms) | Min (ms) | Max (ms) | Peak RSS (MB) |",
            "|---|---|---|---|---|",
        ]

        stages = benchmark_data.get("stages", {})
        for name, stats in stages.items():
            mean_ms = stats.get("mean_ms", 0.0)
            min_ms = stats.get("min_ms", 0.0)
            max_ms = stats.get("max_ms", 0.0)
            rss = stats.get("peak_rss_mb", 0.0)
            lines.append(f"| {name} | {mean_ms:.2f} | {min_ms:.2f} | {max_ms:.2f} | {rss:.2f} |")

        lines.extend([
            "",
            "## Summary Metrics",
            "",
            f"- **Mean End-to-End Latency:** {benchmark_data.get('mean_e2e_ms', 0.0):.2f} ms",
            f"- **Peak RSS Memory:** {benchmark_data.get('overall_peak_rss_mb', 0.0):.2f} MB",
            f"- **Feature Count Generated:** {benchmark_data.get('feature_count', 0)}",
            f"- **Determinism Verification:** {'PASSED ✅' if benchmark_data.get('determinism_passed') else 'FAILED ❌'}",
            "",
            "---",
            "*Report auto-generated by benchmarks/report_generator.py*",
        ])

        p = Path(output_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("\n".join(lines), encoding="utf-8")
